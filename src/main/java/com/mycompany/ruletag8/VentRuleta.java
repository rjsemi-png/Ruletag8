    private void btnGirarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGirarActionPerformed
      int totalGrupos = Integer.parseInt(txtCantidad.getText());
        int numeroAleatorio = 0;
      
      
        if (totalGrupos < 1 || totalGrupos > 10) {
            javax.swing.JOptionPane.showMessageDialog(this, "El número de grupos debe estar entre 1 y 10");
        return;
        }
        
        
        if (cantidadPasados < totalGrupos) {
        boolean repetido;

    
    do {
        repetido = false;
        // Genera un número del 1 al 10
        numeroAleatorio = (int) (Math.random() * totalGrupos) + 1; 

        
        for (int i = 0; i < cantidadPasados; i++) {
                if (gruposPasados[i] == numeroAleatorio) {
                    repetido = true;
                    break;
                }
            }
        } while (repetido); 


        gruposPasados[cantidadPasados] = numeroAleatorio;
        cantidadPasados++;
    

        lblResultado.setText("Grupo: " + numeroAleatorio);
        txtHistorial.append("Pasó el Grupo " + numeroAleatorio + "\n");
    
        } else {
        lblResultado.setText("¡Finalizado!");
    }
      
    }//GEN-LAST:event_btnGirarActionPerformed

